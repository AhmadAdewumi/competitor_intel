def save_pdf(html_content: str, output_path: str) -> bool:
    """
    Save HTML as PDF.

    Args:
        html_content: HTML string
        output_path: Path to save PDF

    Returns:
        True if successful
    """
    try:
        HTML(string=html_content).write_pdf(output_path)
        log.info(f"✅ PDF saved to {output_path}")
        return True
    except Exception as e:
        log.error(f"Failed to generate PDF: {e}")
        return False


def save_html(html_content: str, output_path: str) -> bool:
    """
    Save HTML to file.

    Args:
        html_content: HTML string
        output_path: Path to save HTML

    Returns:
        True if successful
    """
    try:
        with open(output_path, "w") as f:
            f.write(html_content)
        log.info(f"✅ HTML saved to {output_path}")
        return True
    except Exception as e:
        log.error(f"Failed to save HTML: {e}")
        return False

def is_report_meaningful(report_content: str) -> bool:
    """
    Check if a report is meaningful (not empty, not an error message).

    Args:
        report_content: The report content to check

    Returns:
        True if the report is meaningful
    """
    if not report_content or len(report_content.strip()) < 200:
        return False

    # Check for common "no data" messages
    no_data_patterns = [
        "no data available",
        "no content found",
        "no research data",
        "no information found",
        "unable to find",
        "no results found",
        "no memories found",
        "please run the researcher",
        "no additional content",
        "no findings",
    ]

    lower_content = report_content.lower()

    # If the report is mostly an error message, reject it
    for pattern in no_data_patterns:
        if pattern in lower_content:
            # Check if the pattern appears multiple times or is prominent
            if lower_content.count(pattern) > 1:
                return False

    # Check if it has proper structure (headings, sections)
    has_headings = any(mark in report_content for mark in ["#", "##", "###", "**"])

    # Check if it has substantial content
    has_substance = len(report_content.split()) > 150

    return has_headings and has_substance


def extract_report_from_results(results: List[Dict[str, Any]]) -> Optional[str]:
    """
    Extract a report from a list of results.

    Args:
        results: List of result dictionaries from agent context

    Returns:
        The report content or None
    """
    for r in reversed(results):
        if isinstance(r, dict):
            # Try different keys
            for key in ["report", "polished_report", "content", "response"]:
                content = r.get(key)
                if content and isinstance(content, str) and len(content) > 200:
                    # If it's a report, it should have structure
                    if "#" in content or "**" in content or len(content) > 500:
                        return content

    return None