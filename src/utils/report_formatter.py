def markdown_to_html(md_content: str) -> str:
    """
    Convert markdown to HTML.

    Args:
        md_content: Markdown content

    Returns:
        HTML string
    """
    return markdown.markdown(md_content, extensions=["extra", "tables", "fenced_code"])


